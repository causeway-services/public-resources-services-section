#!/usr/bin/env node
import { fileURLToPath } from "node:url";
import { dirname } from "node:path";
import { listDirectoryEntries } from "@red-cup-engineering/computer-filepath-engineering-services-section/list-directory-entries";
import { readFileText } from "@red-cup-engineering/computer-file-engineering-services-section/read-file";
import { writeFileText } from "@red-cup-engineering/computer-file-engineering-services-section/write-file";
import { runJavascriptNodeOperation } from "@red-cup-engineering/javascript-node-services-section/operation";

const PACKAGE_ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const RECORD_SUFFIX = "-energy-price-series.json";

/**
 * Projects the newest `data/records/*-energy-price-series.json` benchmark record into a
 * generated `src/benchmark-latest.mjs` ES module that a separate bundle consumer can import at
 * build time (a bundle runtime has no filesystem, so the record must already be embedded); the
 * one file-copy effect this package performs, reading and writing only through the house file
 * and directory services, never `node:fs` directly.
 * @param {{packageRoot?: string}} [request]
 * @returns {Promise<{sourceRecordPath: string, generatedModulePath: string, asOf: string, rowCount: number}>}
 * @throws {Error} when no `data/records/*-energy-price-series.json` file exists under `packageRoot`
 */
export async function projectBenchmarkLatest(request = {}) {
  const packageRoot = typeof request.packageRoot === "string" && request.packageRoot.length > 0 ? request.packageRoot : PACKAGE_ROOT;
  const listing = await listDirectoryEntries({ root: packageRoot, path: "data/records" });
  const candidateNames = listing.entries
    .filter((entry) => entry.kind === "file" && entry.name.endsWith(RECORD_SUFFIX))
    .map((entry) => entry.name)
    .sort();
  if (candidateNames.length === 0) throw new Error(`project-benchmark-latest: no ${RECORD_SUFFIX} file found under ${packageRoot}/data/records`);
  const latestName = candidateNames.at(-1);
  const sourceRecordPath = `${packageRoot}/data/records/${latestName}`;
  const record = JSON.parse(await readFileText(sourceRecordPath));
  const generatedModulePath = `${packageRoot}/src/benchmark-latest.mjs`;
  const moduleText = `// GENERATED by scripts/project-benchmark-latest.mjs from data/records/${latestName}. Do not hand-edit; re-run the script to refresh.\nexport const BENCHMARK_LATEST = ${JSON.stringify(record, null, 2)};\n`;
  await writeFileText(generatedModulePath, moduleText);
  return Object.freeze({ sourceRecordPath, generatedModulePath, asOf: record.asOf, rowCount: record.rows.length });
}

if (import.meta.main) {
  const result = await runJavascriptNodeOperation({ name: "project-benchmark-latest", description: "Projects the newest `data/records/*-energy-price-series.json` benchmark record into a generated `src/benchmark-latest.mjs` ES module that a separate bundle consumer can import at build time (a bundle runtime has no filesystem, so the record must already be embedded); the one file-copy effect this package performs, reading and writing only through the house file and directory services, never `node:fs` directly.", operation: projectBenchmarkLatest }, { arguments: process.argv.slice(2), standardInput: process.stdin, standardOutput: process.stdout });
  process.exitCode = result.exitCode;
}
